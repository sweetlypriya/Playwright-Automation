//ARITHMETIC OPERATORS

let a=10
let b=5

//+ -> addition
console.log("addition: "+ (a+b))

//- -> subtraction
console.log("subtraction: "+ (a-b))

//* -> multiplication
console.log("multiplication: " + (a*b))

// / -> division
console.log("division: "+(a/b))

//% -> modulus (prints reminder value of the division)
console.log("modulus: "+(a%b))

//++ -> increment
//++a - pre increment (first increase the value and use it)
//a++ - post increment(first use the value and then increase it)

console.log("======INCREMENT======")

console.log(++a) //11 ->a=11
console.log(a++) //11 ->a=12
console.log(a) //12
console.log(a++) //12 ->a=13
console.log(a) //13
console.log(++a) //14 ->a=14
console.log(a) //14

//-- -> decrement
//--a - pre decrement (first decrease the value and use it)
//a-- - post decrement(first use the value and then decrease it)

console.log("=======DECREMENT======")

console.log(--b) //4 ->b=4
console.log(b--) //4 ->b=3
console.log(b--) //3 ->a=2
console.log(--b) //1 ->a=1


