//1)Math.floor() => Rounds down and print (eg: 5.1 to 5.9 o/p:5)
console.log("===========FLOOR========")

console.log(Math.floor(5.98)) //o/p:5
console.log(Math.floor(12.1)) //o/p:12

//2)Math.round() => rounds the decimal to nearest integer
console.log("=========ROUND=======")

console.log(Math.round(2.4)) //2
console.log(Math.round(2.9)) //3

//3)Math.ceil() => Rounds up and print (eg: 5.1 to 5.9 o/p:6)
console.log("========CEIL========")

console.log(Math.ceil(5.98)) //o/p:6
console.log(Math.ceil(12.1)) //o/p:13

//4)Math.random() => generate random numbers
console.log("=======RANDOM========")

console.log(Math.random())

//5)Math.max() => returns the maximum value
console.log("=======MAX======")

console.log(Math.max(45,78,23,8))

//6)Math.min() => returns the minimum value
console.log("========MIN=======")

console.log(Math.min(45,78,23,8))

//7)Math.sqrt() => returns the square root of the value
console.log("======SQRT======")

console.log(Math.sqrt(10))
